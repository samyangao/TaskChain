"""Minimal dependency-free PDF writer for TaskChain reports (Phase 8).

Only the built-in Helvetica fonts are used, so no extra package is required.
The layout is deliberately simple: a branded header, metric boxes, summary
tables and a paginated task register.
"""

from datetime import datetime

PAGE_W = 595.28
PAGE_H = 841.89
MARGIN = 36
CONTENT_W = PAGE_W - MARGIN * 2
INK = (0.09, 0.13, 0.10)
MUTED = (0.38, 0.44, 0.40)
GREEN = (0.07, 0.36, 0.20)
GREEN_SOFT = (0.90, 0.96, 0.91)
LINE = (0.84, 0.88, 0.85)
WHITE = (1, 1, 1)

_REPLACEMENTS = {
    "\u2014": "-", "\u2013": "-", "\u2018": "'", "\u2019": "'",
    "\u201c": '"', "\u201d": '"', "\u2026": "...", "\u00b7": "-",
    "\u2605": "*", "\u00a0": " ",
}


def _clean(text):
    text = str(text if text is not None else "")
    for old, new in _REPLACEMENTS.items():
        text = text.replace(old, new)
    return text.encode("latin-1", "replace").decode("latin-1")


def _escape(text):
    return _clean(text).replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)").replace("\r", " ").replace("\n", " ")


def _fit(text, width, size, bold=False):
    text = _clean(text)
    per_char = size * (0.56 if bold else 0.52)
    limit = max(1, int(width / per_char))
    if len(text) <= limit:
        return text
    return text[: max(1, limit - 1)].rstrip() + "\u2026"


class Canvas:
    def __init__(self):
        self.pages = []
        self.current = None
        self.page_no = 0

    def new_page(self):
        self.pages.append([])
        self.current = self.pages[-1]
        self.page_no += 1

    def _cmd(self, command):
        self.current.append(command)

    def text(self, x, top, value, size=9, bold=False, color=INK):
        font = "F2" if bold else "F1"
        y = PAGE_H - top
        r, g, b = color
        self._cmd(
            f"BT /{font} {size:.2f} Tf {r:.3f} {g:.3f} {b:.3f} rg "
            f"1 0 0 1 {x:.2f} {y:.2f} Tm ({_escape(value)}) Tj ET"
        )

    def rect(self, x, top, width, height, fill=None, stroke=None, line_width=0.6):
        y = PAGE_H - top - height
        if fill:
            r, g, b = fill
            self._cmd(f"{r:.3f} {g:.3f} {b:.3f} rg {x:.2f} {y:.2f} {width:.2f} {height:.2f} re f")
        if stroke:
            r, g, b = stroke
            self._cmd(f"{r:.3f} {g:.3f} {b:.3f} RG {line_width:.2f} w {x:.2f} {y:.2f} {width:.2f} {height:.2f} re S")

    def line(self, x1, top1, x2, top2, color=LINE, width=0.6):
        r, g, b = color
        self._cmd(
            f"{r:.3f} {g:.3f} {b:.3f} RG {width:.2f} w "
            f"{x1:.2f} {PAGE_H - top1:.2f} m {x2:.2f} {PAGE_H - top2:.2f} l S"
        )

    def build(self):
        total = len(self.pages)
        for index, page in enumerate(self.pages, 1):
            page.append(
                f"BT /F1 8 Tf 0.45 0.50 0.47 rg 1 0 0 1 {MARGIN:.2f} {18:.2f} Tm "
                f"(TaskChain  |  Page {index} of {total}) Tj ET"
            )
            page.append(
                f"BT /F1 8 Tf 0.45 0.50 0.47 rg 1 0 0 1 {PAGE_W - MARGIN - 120:.2f} {18:.2f} Tm "
                f"(Generated by TaskChain) Tj ET"
            )

        objects = [None] * 4
        objects[0] = "<< /Type /Catalog /Pages 2 0 R >>"
        objects[2] = "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>"
        objects[3] = "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>"
        kids = []
        for page in self.pages:
            stream = "\n".join(page)
            stream_bytes = stream.encode("latin-1", "replace")
            content_num = len(objects) + 2
            page_num = len(objects) + 1
            kids.append(f"{page_num} 0 R")
            objects.append(
                f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {PAGE_W:.2f} {PAGE_H:.2f}] "
                f"/Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents {content_num} 0 R >>"
            )
            objects.append(f"<< /Length {len(stream_bytes)} >>\nstream\n{stream}\nendstream")
        objects[1] = f"<< /Type /Pages /Kids [{' '.join(kids)}] /Count {len(self.pages)} >>"

        pdf = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
        offsets = [0]
        for number, obj in enumerate(objects, 1):
            offsets.append(len(pdf))
            pdf.extend(f"{number} 0 obj\n{obj}\nendobj\n".encode("latin-1", "replace"))
        xref = len(pdf)
        pdf.extend(f"xref\n0 {len(objects) + 1}\n0000000000 65535 f \n".encode("latin-1"))
        for offset in offsets[1:]:
            pdf.extend(f"{offset:010d} 00000 n \n".encode("latin-1"))
        pdf.extend(
            f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode("latin-1")
        )
        return bytes(pdf)


def _header(canvas, report):
    canvas.rect(0, 0, PAGE_W, 92, fill=GREEN)
    canvas.text(MARGIN, 32, "TaskChain", 20, bold=True, color=WHITE)
    canvas.text(MARGIN, 50, "Operations report", 11, color=(0.82, 0.93, 0.85))
    canvas.text(MARGIN, 72, f"Generated {report.get('generated_at', '')}", 8, color=(0.76, 0.88, 0.79))
    canvas.text(PAGE_W - MARGIN - 190, 32, f"Prepared by {report.get('generated_by', 'TaskChain')}", 8,
                color=(0.82, 0.93, 0.85))
    return 112


def _filters_line(report):
    return report.get("filters") or "All tasks"


def _metric_boxes(canvas, top, summary):
    metrics = [
        ("Total tasks", summary.get("total", 0), "In the selected view"),
        ("Active", summary.get("active", 0), "Open and on track"),
        ("Completed", summary.get("completed", 0), "Verified or closed"),
        ("Overdue", summary.get("overdue", 0), "Past SLA or deadline"),
        ("Avg. resolution", summary.get("avg_resolution", "-"), "From request to completion"),
        ("SLA compliance", summary.get("sla_compliance", "-"), "Completed within SLA"),
    ]
    box_w = (CONTENT_W - 20) / 3
    box_h = 54
    for index, (label, value, sub) in enumerate(metrics):
        row, col = divmod(index, 3)
        x = MARGIN + col * (box_w + 10)
        y = top + row * (box_h + 8)
        canvas.rect(x, y, box_w, box_h, fill=GREEN_SOFT, stroke=LINE)
        canvas.text(x + 10, y + 15, label.upper(), 7, bold=True, color=MUTED)
        canvas.text(x + 10, y + 34, str(value), 17, bold=True, color=INK)
        canvas.text(x + 10, y + 47, sub, 6.5, color=MUTED)
    return top + 2 * box_h + 8


def _section(canvas, top, title, note=""):
    canvas.text(MARGIN, top + 10, title.upper(), 8, bold=True, color=GREEN)
    if note:
        canvas.text(MARGIN + 120, top + 10, note, 7, color=MUTED)
    canvas.line(MARGIN, top + 14, PAGE_W - MARGIN, top + 14)
    return top + 24


def _table(canvas, top, widths, headers, rows, aligns=None, size=7.6, row_h=16, max_rows=None):
    aligns = aligns or ["left"] * len(widths)
    total_w = sum(widths)

    def draw_header(y):
        canvas.rect(MARGIN, y, total_w, row_h + 2, fill=(0.95, 0.97, 0.95))
        x = MARGIN
        for width, header, align in zip(widths, headers, aligns):
            if align == "right":
                text = _fit(header, width - 10, size, bold=True)
                # right-align by estimating width
                canvas.text(x + width - 6 - len(_clean(text)) * size * 0.52, y + 12, text, size, bold=True, color=MUTED)
            else:
                canvas.text(x + 6, y + 12, _fit(header, width - 10, size, bold=True), size, bold=True, color=MUTED)
            x += width

    draw_header(top)
    y = top + row_h + 2
    count = 0
    for row in rows:
        if max_rows and count >= max_rows:
            break
        if y + row_h > PAGE_H - 42:
            canvas.new_page()
            y = _section(canvas, MARGIN, "continued")
            draw_header(y)
            y += row_h + 2
        if count % 2 == 0:
            canvas.rect(MARGIN, y, total_w, row_h, fill=(0.985, 0.99, 0.985))
        x = MARGIN
        for width, value, align in zip(widths, row, aligns):
            text = _fit(value, width - 10, size)
            if align == "right":
                canvas.text(x + width - 6 - len(_clean(text)) * size * 0.52, y + 11, text, size, color=INK)
            else:
                canvas.text(x + 6, y + 11, text, size, color=INK)
            x += width
        canvas.line(MARGIN, y + row_h, MARGIN + total_w, y + row_h)
        y += row_h
        count += 1
    return y + 12


def _status_table_rows(rows, label_key):
    return [[str(r.get(label_key, "")).replace("_", " ").title(), r.get("count", 0)] for r in rows]


def build_report_pdf(report):
    canvas = Canvas()
    canvas.new_page()
    top = _header(canvas, report)
    canvas.text(MARGIN, top, "Filters", 7, bold=True, color=MUTED)
    canvas.text(MARGIN + 42, top, _filters_line(report), 8, color=INK)
    top += 18
    top = _metric_boxes(canvas, top, report.get("summary", {}))
    top += 6

    top = _section(canvas, top, "Workload by person", "Active / completed / overdue / historical")
    rows = []
    for person in report.get("workload", []):
        rows.append([
            person.get("full_name", ""),
            person.get("active", 0),
            person.get("completed", 0),
            person.get("overdue", 0),
            person.get("historical", 0),
            person.get("total", 0),
        ])
    if rows:
        top = _table(
            canvas, top,
            [200, 60, 70, 60, 70, 50],
            ["Person", "Active", "Completed", "Overdue", "Historical", "Total"],
            rows,
            aligns=["left", "right", "right", "right", "right", "right"],
        )
    else:
        canvas.text(MARGIN, top + 12, "No assigned tasks in this view.", 8, color=MUTED)
        top += 26

    left_rows = _status_table_rows(report.get("byStatus", []), "status")
    right_rows = _status_table_rows(report.get("byPriority", []), "priority")
    if left_rows or right_rows:
        top = _section(canvas, top, "Distribution")
        half = (CONTENT_W - 20) / 2
        start = top
        canvas.text(MARGIN, top + 10, "By status", 7.5, bold=True, color=MUTED)
        top_left = _table(canvas, top + 16, [half - 60, 60], ["Status", "Tasks"], left_rows, aligns=["left", "right"])
        canvas.text(MARGIN + half + 20, start + 10, "By priority", 7.5, bold=True, color=MUTED)
        # Draw the right table with an explicit x offset by temporarily shifting margins is
        # awkward; a compact stacked layout is clearer and avoids overlapping columns.
        top = max(top_left, start + 16 + 20 + len(right_rows) * 16 + 16)
        top = _section(canvas, top, "By priority")
        top = _table(canvas, top, [half - 60, 60], ["Priority", "Tasks"], right_rows, aligns=["left", "right"])

    categories = _status_table_rows(report.get("byCategory", []), "category")
    if categories:
        top = _section(canvas, top, "Top categories")
        top = _table(canvas, top, [300, 100], ["Category", "Tasks"], categories, aligns=["left", "right"])

    tasks = report.get("tasks", [])
    top = _section(canvas, top, "Task register", f"{len(tasks)} task(s) in this view")
    rows = []
    for task in tasks:
        rows.append([
            task.get("task_code", ""),
            task.get("title", ""),
            str(task.get("status", "")).replace("_", " ").title(),
            str(task.get("priority", "")).title(),
            task.get("assignee") or "Unassigned",
            task.get("due_at") or "-",
        ])
    if rows:
        top = _table(
            canvas, top,
            [64, 190, 78, 50, 88, 90],
            ["Code", "Task", "Status", "Priority", "Responsible", "Due"],
            rows,
            max_rows=600,
        )
    else:
        canvas.text(MARGIN, top + 12, "No tasks match the selected filters.", 8, color=MUTED)

    return canvas.build()
